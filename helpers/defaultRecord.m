function d = defaultRecord(config)
% DEFAULTRECORD  Canonical event record with all required log fields.
% Text fields are MATLAB `string` (empty ""), numeric fields are double NaN.
% The field ORDER here defines the CSV column order.
d = struct( ...
    'subjectID',           string(config.subjectID), ...
    'sessionID',           string(config.sessionID), ...
    'taskName',            "", ...
    'blockNumber',         NaN, ...
    'blockType',           "", ...     % active | control | rest
    'trialNumber',         NaN, ...
    'stimulus',            "", ...
    'correctAnswer',       "", ...
    'participantResponse', "", ...
    'accuracy',            NaN, ...
    'reactionTime',        NaN, ...
    'eventName',           "", ...
    'eventOnsetGetSecs',   NaN, ...   % raw PTB clock (origin = machine boot)
    'eventOnsetRelative',  NaN, ...   % s since sync t0 -- USE THIS TO ALIGN
    'eventDuration',       NaN, ...
    'triggerCode',         NaN);
end
