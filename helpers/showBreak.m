function showBreak(win, config, taskName)
% SHOWBREAK  Short end-of-task break screen (SPACE skips, Escape aborts).
msg = sprintf(['End of task: %s\n\n' ...
               'Take a short break.\n\n' ...
               'The experiment will continue automatically,\n' ...
               'or press SPACE to continue now.'], taskName);
showTimedScreen(win, config, msg, config.breakDuration, true);
end
